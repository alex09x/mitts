"""Page shell shared by the generated site pages."""
import html

NAV = [("Docs", "docs/"), ("How it works", "docs/#how-it-works"), ("The Hundred", "hundred/"),
       ("GitHub", "https://github.com/alex09x/mitts")]


def esc(s):
    return html.escape(str(s), quote=True)


def page(title, description, body, depth, extra_head="", active=""):
    """Wrap `body` in the site shell. `depth` is the number of path segments below site/."""
    up = "../" * depth
    nav = "".join(
        '<a href="%s"%s>%s</a>' % (h if h.startswith("http") else up + h,
                                   ' aria-current="page"' if n == active else "", n)
        for n, h in NAV)
    return """<!doctype html>
<!--
 * Mitts Build - project website (generated by scripts/site/build.py, do not edit)
 * Copyright (c) 2026 Alexander Panasenko
 *
 * Contact: alex@prod.codes
 * Author: https://prod.codes/about/
 * Project: https://github.com/alex09x/mitts
 * SPDX-License-Identifier: MIT OR Apache-2.0
 -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#121315">
  <meta name="description" content="%(desc)s">
  <title>%(title)s</title>
  <link rel="icon" href="%(up)sfavicon.ico?v=3" sizes="any">
  <link rel="icon" href="%(up)slogo.svg?v=3" type="image/svg+xml">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,500;12..96,700;12..96,800&family=IBM+Plex+Sans:wght@400;500&family=JetBrains+Mono:wght@400;600&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="%(up)sstyles.css">
  <link rel="stylesheet" href="%(up)spages.css">
  <link rel="stylesheet" href="%(up)shundred.css">
%(extra)s</head>
<body>
  <script>document.documentElement.classList.add("js")</script>
  <header class="shell topbar">
    <a class="brand" href="%(home)s" aria-label="Mitts home">
      <img class="mark" src="%(up)slogo.svg?v=3" alt="" width="20" height="20">
      <span>mitts<span class="dim">/build</span></span>
    </a>
    <nav class="nav" aria-label="Main navigation">%(nav)s</nav>
  </header>
%(body)s
  <footer class="shell foot">
    <span>Mitts Build &middot; MIT OR Apache-2.0 &middot; <a href="https://prod.codes/about/">Alexander Panasenko</a></span>
    <span><a href="https://github.com/alex09x/mitts">GitHub</a> &middot; <a href="https://crates.io/crates/mitts">crates.io</a></span>
  </footer>
</body>
</html>
""" % {"title": esc(title), "desc": esc(description), "up": up, "home": up or "./", "nav": nav,
       "body": body, "extra": extra_head}
