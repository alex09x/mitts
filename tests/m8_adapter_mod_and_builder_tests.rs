use mitts::adapter::rust::fetcher::FetchOptions;
use mitts::adapter::rust::types::RustBuildOptions;
use mitts::adapter::RustAdapter;
use mitts::core::source_store::SourceStore;
use std::fs;
use tempfile::TempDir;

#[test]
fn test_m8_adapter_toolchain_detection_and_cache() {
    let tmp = TempDir::new().unwrap();
    let old_home = std::env::var("HOME").ok();
    std::env::set_var("HOME", tmp.path().to_str().unwrap());

    // First detection writes cache
    let info1 = RustAdapter::detect_toolchain().unwrap();
    assert_eq!(info1.name, "rustc");
    assert!(!info1.version.is_empty());

    // Second detection should hit the cache
    let info2 = RustAdapter::detect_toolchain().unwrap();
    assert_eq!(info1.version, info2.version);
    assert_eq!(info1.target_triple, info2.target_triple);

    if let Some(h) = old_home {
        std::env::set_var("HOME", h);
    }
}

#[test]
fn test_m8_adapter_resolve_manifest_and_target_dir() {
    let tmp = TempDir::new().unwrap();
    let cargo_toml = tmp.path().join("Cargo.toml");
    fs::write(
        &cargo_toml,
        "[package]\nname = \"mod-test\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();

    // Absolute path
    let opt_abs = RustBuildOptions {
        manifest_path: Some(cargo_toml.clone()),
        ..Default::default()
    };
    let resolved_abs = RustAdapter::resolve_manifest(&opt_abs).unwrap();
    assert_eq!(resolved_abs, cargo_toml);

    // Missing manifest error
    let opt_missing = RustBuildOptions {
        manifest_path: Some(tmp.path().join("NonExistent.toml")),
        ..Default::default()
    };
    assert!(RustAdapter::resolve_manifest(&opt_missing).is_err());

    // Target dir: Some
    let custom_target = tmp.path().join("custom_target");
    let opt_target = RustBuildOptions {
        target_dir: Some(custom_target.clone()),
        ..Default::default()
    };
    let resolved_target = RustAdapter::resolve_target_dir(&cargo_toml, &opt_target).unwrap();
    assert_eq!(resolved_target, custom_target);

    // Target dir: None -> fallback to .mitts/target
    let opt_no_target = RustBuildOptions::default();
    let default_target = RustAdapter::resolve_target_dir(&cargo_toml, &opt_no_target).unwrap();
    assert_eq!(default_target, tmp.path().join("target").join("mitts"));
}

#[test]
fn test_m8_adapter_lockfile_and_fetch() {
    let tmp = TempDir::new().unwrap();
    let cargo_toml = tmp.path().join("Cargo.toml");
    fs::write(
        &cargo_toml,
        "[package]\nname = \"fetch-test\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    let cargo_lock = tmp.path().join("Cargo.lock");
    fs::write(
        &cargo_lock,
        "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"fetch-test\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();

    let lock = RustAdapter::resolve_lockfile(&cargo_toml, true, None).unwrap();
    assert_eq!(lock.packages.len(), 1);
    assert_eq!(lock.packages[0].name, "fetch-test");

    let store = SourceStore::new(tmp.path().join("sources")).unwrap();
    let fetch_opt = FetchOptions {
        offline: true,
        locked: false,
        frozen: false,
    };
    let res = RustAdapter::fetch(&cargo_toml, &store, &fetch_opt, None).unwrap();
    assert_eq!(res.fetched, 0);
}

#[test]
fn test_m8_builder_cargo_fallback_and_no_cache() {
    let tmp = TempDir::new().unwrap();
    let cargo_toml = tmp.path().join("Cargo.toml");
    fs::write(
        &cargo_toml,
        "[package]\nname = \"cargo-fallback-test\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    let src_dir = tmp.path().join("src");
    fs::create_dir_all(&src_dir).unwrap();
    fs::write(src_dir.join("main.rs"), "fn main() {}").unwrap();

    let opt = RustBuildOptions {
        manifest_path: Some(cargo_toml),
        cargo: true,
        no_cache: true,
        target_dir: Some(tmp.path().join("target")),
        cache_dir: Some(tmp.path().join("cache")),
        ..Default::default()
    };

    let res = RustAdapter::build(&opt);
    assert!(res.is_ok(), "build returned Err: {:?}", res.err());
    let (plan, action_res) = res.unwrap();
    assert!(
        action_res.success,
        "Build failed: stdout={}, stderr={}",
        action_res.stdout, action_res.stderr
    );
    assert!(!plan.actions.is_empty());
}
