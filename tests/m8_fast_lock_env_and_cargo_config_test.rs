static SERIAL_TEST_LOCK: Mutex<()> = Mutex::new(());

struct EnvGuard {
    cargo_home_orig: Option<std::ffi::OsString>,
}

impl EnvGuard {
    fn new(isolated_cargo_home: &std::path::Path) -> Self {
        let cargo_home_orig = std::env::var_os("CARGO_HOME");
        std::env::set_var("CARGO_HOME", isolated_cargo_home);
        std::env::remove_var("CARGO_ENCODED_RUSTFLAGS");
        std::env::remove_var("RUSTFLAGS");
        std::env::remove_var("CARGO_BUILD_RUSTFLAGS");
        let host = resolve_host_triple();
        let upper_triple = host.replace('-', "_").to_uppercase();
        std::env::remove_var(format!("CARGO_TARGET_{}_RUSTFLAGS", upper_triple));
        Self { cargo_home_orig }
    }
}

impl Drop for EnvGuard {
    fn drop(&mut self) {
        if let Some(ref orig) = self.cargo_home_orig {
            std::env::set_var("CARGO_HOME", orig);
        } else {
            std::env::remove_var("CARGO_HOME");
        }
        std::env::remove_var("CARGO_BUILD_RUSTFLAGS");
        let host = resolve_host_triple();
        let upper_triple = host.replace('-', "_").to_uppercase();
        std::env::remove_var(format!("CARGO_TARGET_{}_RUSTFLAGS", upper_triple));
    }
}

#[test]
fn test_fast_lock_env_hash_invalidation() {
    let _lock = SERIAL_TEST_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let temp = TempDir::new().unwrap();
    let proj_dir = temp.path();

    // Create minimal Cargo project structure
    fs::write(
        proj_dir.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 3\n",
    )
    .unwrap();
    fs::create_dir_all(proj_dir.join("src")).unwrap();
    fs::write(
        proj_dir.join("src/lib.rs"),
        "pub fn hello() -> &'static str { \"hello\" }",
    )
    .unwrap();

    // Ensure test environment baseline
    std::env::remove_var("CARGO_ENCODED_RUSTFLAGS");
    std::env::remove_var("RUSTC_WRAPPER");
    std::env::remove_var("RUSTFLAGS");

    // 1. Record state with baseline environment
    let record_args = RecordStateArgs {
        project_dir: proj_dir,
        profile: "dev",
        package: &None,
        features: &[],
        no_default_features: false,
        all_features: false,
        toolchain_version: "rustc 1.80.0",
        action_count: 1,
        root_binary: None,
        outputs: &[],
        stderr: None,
    };
    FastBuildLock::record_state(&record_args).unwrap();

    let check_args = FreshnessCheckArgs {
        project_dir: proj_dir,
        profile: "dev",
        package: &None,
        features: &[],
        no_default_features: false,
        all_features: false,
        toolchain_version: "rustc 1.80.0",
    };

    // Baseline freshness check should be fresh
    match FastBuildLock::check_freshness(&check_args) {
        FreshnessResult::Fresh { .. } => {}
        res => panic!("Expected Fresh, got {:?}", res),
    }

    // 2. Set CARGO_ENCODED_RUSTFLAGS -> should detect stale
    std::env::set_var(
        "CARGO_ENCODED_RUSTFLAGS",
        "--cfg\x1fcustom_test_env_flag_active",
    );
    match FastBuildLock::check_freshness(&check_args) {
        FreshnessResult::Stale(ref reason) => {
            assert!(
                reason.contains("Environment configuration changed"),
                "Expected env stale reason, got: {}",
                reason
            );
        }
        res => panic!(
            "Expected Stale on CARGO_ENCODED_RUSTFLAGS change, got {:?}",
            res
        ),
    }
    std::env::remove_var("CARGO_ENCODED_RUSTFLAGS");

    // Fresh again after removal
    match FastBuildLock::check_freshness(&check_args) {
        FreshnessResult::Fresh { .. } => {}
        res => panic!("Expected Fresh after resetting env, got {:?}", res),
    }

    // 3. Set RUSTC_WRAPPER -> should detect stale
    std::env::set_var("RUSTC_WRAPPER", "sccache");
    match FastBuildLock::check_freshness(&check_args) {
        FreshnessResult::Stale(ref reason) => {
            assert!(
                reason.contains("Environment configuration changed"),
                "Expected env stale reason, got: {}",
                reason
            );
        }
        res => panic!("Expected Stale on RUSTC_WRAPPER change, got {:?}", res),
    }
    std::env::remove_var("RUSTC_WRAPPER");

    // 4. Set RUSTFLAGS -> should detect stale
    std::env::set_var("RUSTFLAGS", "-C opt-level=2");
    match FastBuildLock::check_freshness(&check_args) {
        FreshnessResult::Stale(ref reason) => {
            assert!(
                reason.contains("Environment configuration changed"),
                "Expected env stale reason, got: {}",
                reason
            );
        }
        res => panic!("Expected Stale on RUSTFLAGS change, got {:?}", res),
    }
    std::env::remove_var("RUSTFLAGS");
}

#[test]
fn test_cargo_config_rustflags_discovery_and_precedence() {
    let _lock = SERIAL_TEST_LOCK.lock().unwrap();
    let temp = TempDir::new().unwrap();
    let root = temp.path();
    let _guard = EnvGuard::new(&root.join("empty_cargo_home"));

    let pkg_dir = root.join("crates/sub_crate");
    fs::create_dir_all(&pkg_dir).unwrap();

    let host_triple = resolve_host_triple();
    let other_triple = if host_triple == "aarch64-apple-darwin" {
        "x86_64-unknown-linux-gnu"
    } else {
        "aarch64-apple-darwin"
    };

    // Create .cargo/config.toml at root with [build] and [target]
    let cargo_dir = root.join(".cargo");
    fs::create_dir_all(&cargo_dir).unwrap();
    fs::write(
        cargo_dir.join("config.toml"),
        format!(
            r#"
[build]
rustflags = ["--cfg", "fallback_config_flag"]

[target.'{}']
rustflags = "-C target-cpu=native --cfg other_specific_flag"

[target.'{}']
rustflags = ["--cfg", "host_specific_flag"]
"#,
            other_triple, host_triple
        ),
    )
    .unwrap();

    // 1. Target triple matching other_triple (string syntax)
    let flags_other = load_cargo_config_rustflags(&pkg_dir, Some(other_triple)).unwrap();
    assert_eq!(
        flags_other,
        vec!["-C", "target-cpu=native", "--cfg", "other_specific_flag"]
    );

    // 2. Unknown target triple falls back to [build].rustflags
    let flags_fallback =
        load_cargo_config_rustflags(&pkg_dir, Some("wasm32-unknown-unknown")).unwrap();
    assert_eq!(flags_fallback, vec!["--cfg", "fallback_config_flag"]);

    // 3. None target triple automatically resolves to host triple!
    let flags_none = load_cargo_config_rustflags(&pkg_dir, None).unwrap();
    assert_eq!(flags_none, vec!["--cfg", "host_specific_flag"]);
}

#[test]
fn test_cargo_config_hierarchical_merging() {
    let _lock = SERIAL_TEST_LOCK.lock().unwrap();
    let temp = TempDir::new().unwrap();
    let root = temp.path();

    let pkg_dir = root.join("workspace").join("child_crate");
    fs::create_dir_all(&pkg_dir).unwrap();

    // Parent .cargo/config.toml
    let parent_cargo = root.join("workspace").join(".cargo");
    fs::create_dir_all(&parent_cargo).unwrap();
    fs::write(
        parent_cargo.join("config.toml"),
        r#"
[build]
rustflags = ["-C", "opt-level=2"]
"#,
    )
    .unwrap();

    // Child .cargo/config.toml
    let child_cargo = pkg_dir.join(".cargo");
    fs::create_dir_all(&child_cargo).unwrap();
    fs::write(
        child_cargo.join("config.toml"),
        r#"
[build]
rustflags = ["-C", "target-cpu=native"]
"#,
    )
    .unwrap();

    let flags = load_cargo_config_rustflags(&pkg_dir, Some("unknown-target")).unwrap();
    assert_eq!(
        flags,
        vec!["-C", "opt-level=2", "-C", "target-cpu=native"],
        "Flags from parent and child should be concatenated in precedence order"
    );
}

#[test]
fn test_cargo_config_target_cfg_fails_closed() {
    let _lock = SERIAL_TEST_LOCK.lock().unwrap();
    let temp = TempDir::new().unwrap();
    let root = temp.path();
    let pkg_dir = root.join("pkg");
    fs::create_dir_all(&pkg_dir).unwrap();

    let cargo_dir = pkg_dir.join(".cargo");
    fs::create_dir_all(&cargo_dir).unwrap();
    fs::write(
        cargo_dir.join("config.toml"),
        r#"
[target.'cfg(any(unix, windows))']
rustflags = ["--cfg", "host_matched"]

[target.'cfg(all(windows, target_env = "msvc"))']
rustflags = ["-C", "target-feature=+crt-static"]
"#,
    )
    .unwrap();

    let flags = load_cargo_config_rustflags(&pkg_dir, None).unwrap();
    assert!(flags.contains(&"host_matched".to_string()));

    fs::write(
        cargo_dir.join("config.toml"),
        r#"
[target.'cfg(unsupported_pred(foo))']
rustflags = ["--cfg", "bad_cfg"]
"#,
    )
    .unwrap();
    let res = load_cargo_config_rustflags(&pkg_dir, None);
    assert!(
        res.is_err(),
        "Expected fail-closed error for invalid target.'cfg(...)' syntax"
    );
}

#[test]
fn test_compiler_end_to_end_cargo_config_integration() {
    let isolated_cache = tempfile::tempdir().expect("isolated cache dir");
    let _lock = SERIAL_TEST_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let temp = TempDir::new().unwrap();
    let root = temp.path();
    let _guard = EnvGuard::new(&root.join("empty_cargo_home"));

    fs::create_dir_all(root.join("src")).unwrap();
    fs::create_dir_all(root.join(".cargo")).unwrap();

    fs::write(
        root.join("Cargo.toml"),
        r#"[package]
name = "config_test_pkg"
version = "0.1.0"
edition = "2021"
"#,
    )
    .unwrap();

    // Code requires `custom_config_active` cfg or fails compilation
    fs::write(
        root.join("src/lib.rs"),
        r#"
#[cfg(not(custom_config_active))]
compile_error!("custom_config_active cfg flag was not passed from cargo config!");

pub fn test_val() -> u32 { 100 }
"#,
    )
    .unwrap();

    // Provide the required cfg flag in .cargo/config.toml
    fs::write(
        root.join(".cargo/config.toml"),
        r#"
[build]
rustflags = ["--cfg", "custom_config_active"]
"#,
    )
    .unwrap();

    let opt = RustBuildOptions {
        cache_dir: Some(isolated_cache.path().to_path_buf()),
        manifest_path: Some(root.join("Cargo.toml")),
        mode: BuildMode::Check,
        ..Default::default()
    };

    let check_res = RustAdapter::build(&opt);
    assert!(
        check_res.is_ok(),
        "Expected RustAdapter::build to succeed with config rustflags: {:?}",
        check_res
    );
    let (_plan, result) = check_res.unwrap();
    assert!(
        result.success,
        "Check should succeed with custom_config_active cfg enabled: stderr: {}",
        result.stderr
    );
    assert_eq!(result.exit_code, 0);
}

#[test]
fn test_fast_lock_cargo_config_invalidation() {
    let isolated_cache = tempfile::tempdir().expect("isolated cache dir");
    let _lock = SERIAL_TEST_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let temp = TempDir::new().unwrap();
    let root = temp.path();
    let _guard = EnvGuard::new(&root.join("empty_cargo_home"));

    fs::create_dir_all(root.join("src")).unwrap();
    fs::create_dir_all(root.join(".cargo")).unwrap();

    fs::write(
        root.join("Cargo.toml"),
        r#"[package]
name = "lock_config_test"
version = "0.1.0"
edition = "2021"
"#,
    )
    .unwrap();

    fs::write(
        root.join("src/lib.rs"),
        r#"
#[cfg(custom_failing_flag)]
compile_error!("custom_failing_flag was triggered!");

pub fn run() {}
"#,
    )
    .unwrap();

    let cfg_path = root.join(".cargo/config.toml");
    fs::write(&cfg_path, "[build]\nrustflags = []\n").unwrap();

    std::env::remove_var("CARGO_ENCODED_RUSTFLAGS");
    std::env::remove_var("RUSTFLAGS");

    let opt = RustBuildOptions {
        cache_dir: Some(isolated_cache.path().to_path_buf()),
        fast_lock: Some(true),
        manifest_path: Some(root.join("Cargo.toml")),
        mode: BuildMode::Check,
        ..Default::default()
    };

    // First build succeeds and establishes fast-lock
    let res1 = RustAdapter::build(&opt).unwrap();
    assert!(res1.1.success);

    // Modifying .cargo/config.toml to introduce failing cfg flag
    std::thread::sleep(std::time::Duration::from_millis(20));
    fs::write(
        &cfg_path,
        r#"
[build]
rustflags = ["--cfg", "custom_failing_flag"]
"#,
    )
    .unwrap();

    // FastBuildLock check should detect modified config and invalidate lock
    let toolchain = RustAdapter::detect_toolchain().unwrap();
    let check_args = FreshnessCheckArgs {
        project_dir: root,
        profile: "check",
        package: &None,
        features: &[],
        no_default_features: false,
        all_features: false,
        toolchain_version: &toolchain.version,
    };
    match FastBuildLock::check_freshness(&check_args) {
        FreshnessResult::Stale(ref r) => {
            assert!(
                r.contains("Cargo config modified"),
                "Expected config modified reason, got: {}",
                r
            );
        }
        res => panic!("Expected Stale on config modification, got {:?}", res),
    }

    // Re-running mitts check should re-execute compiler and fail with compile_error!
    let res2 = RustAdapter::build(&opt).unwrap();
    assert!(
        !res2.1.success,
        "Expected build failure after config introduced failing flag"
    );
    assert!(res2.1.stderr.contains("custom_failing_flag was triggered!"));
}
